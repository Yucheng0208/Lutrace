  const SUPPORTED = [
    { code: 'zh-Hant', label: '繁體中文', html: 'zh-Hant', geo: 'zh-Hant,zh-TW,zh' },
    { code: 'en', label: 'English', html: 'en', geo: 'en' },
    { code: 'ja', label: '日本語', html: 'ja', geo: 'ja,en' },
  ];
  const STORE_KEY = 'guanghen.lang';

  function match(tag) {
    const t = String(tag || '').toLowerCase();
    if (t.startsWith('zh')) return 'zh-Hant';
    if (t.startsWith('ja')) return 'ja';
    if (t.startsWith('en')) return 'en';
    return null;
  }
  function detect() {
    const prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
    for (const p of prefs) { const m = match(p); if (m) return m; }
    return null;
  }
  function stored() { try { return localStorage.getItem(STORE_KEY); } catch (e) { return null; } }

  let lang = DICT[stored()] ? stored() : (detect() || 'en');

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
    return s;
  }

  function apply(root) {
    const info = SUPPORTED.find((l) => l.code === lang);
    document.documentElement.lang = info.html;
    const r = root || document;
    r.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    r.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    r.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    r.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    const meta = document.querySelector('meta[name=description]');
    if (meta) meta.content = t('meta.description');
    const h1 = document.getElementById('brand-name');
    if (h1) {
      h1.innerHTML = lang === 'en' ? '<span class="pop">LUTRACE</span>'
        : lang === 'ja' ? '<span class="brand-zh"><ruby>光痕<rt>こうこん</rt></ruby></span>'
        : '<span class="brand-zh">光痕</span>';
    }
    document.title = `${t('app.name')} — ${t('app.tagline')}`;
  }

  function setLang(code) {
    if (!DICT[code]) return;
    lang = code;
    try { localStorage.setItem(STORE_KEY, code); } catch (e) { /* 無痕模式 */ }
    apply();
    window.dispatchEvent(new CustomEvent('langchange', { detail: code }));
  }

  window.I18n = {
    t, apply, setLang, SUPPORTED,
    get lang() { return lang; },
    get geoLang() { return SUPPORTED.find((l) => l.code === lang).geo; },
  };
